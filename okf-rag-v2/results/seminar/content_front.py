ABSTRACT = (
 'Retrieval-augmented generation grounds language model output in retrieved text, yet nearly '
 'every deployed system retrieves fixed-size chunks that begin mid-sentence and carry no '
 'relationship to one another. This study tests whether curating documents into an Open Knowledge '
 'Format bundle — small, self-contained, cross-linked concept units — reduces '
 'hallucination. Two arms answered an identical question set over the same forty-document '
 'Kubernetes corpus, using the same generator, seed and 1,800-token context budget; only the '
 'retrieval substrate differed. The comparison ran twice, first with Llama 3.1 8B over a '
 '371-concept bundle (n=60) and again with Nemotron-3.5-Lightning-30B over a freshly extracted '
 '358-concept bundle judged by an independent model (n=65). Curation produced no statistically '
 'detectable change in hallucination in either configuration: 0.0333 against 0.0833 (p=0.31) and '
 '0.0308 against 0.0154 (p=0.60), with the sign reversing between runs. It did cut retrieval '
 'context by 28.0% and 10.4% at unchanged answer quality. Hand-grading 100 links explains the '
 'null: alias-derived links, the majority of the graph, are 31.5% strictly precise against 77.8% '
 'for title-derived links.')

